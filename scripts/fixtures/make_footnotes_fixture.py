"""
Builds tests/fixtures/linking/footnotes/midrash-vayisau.json: the one real main/notes pair of the
library that is linked with FOOTNOTES, as golden input for the footnotes engine (stage 8.3).

    py -3 -I scripts/fixtures/make_footnotes_fixture.py C:/ProgramData/otzaria/books/seforim.db

The source is opened read-only (mode=ro). Output: every line of both books (stored content, as the
app reads it, with heading level and heRef) and every FOOTNOTES link between them (0-based line
indexes, stored direction). Needs the `zstandard` package for compressed line_content.
"""
import json
import os
import sqlite3
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "C:/ProgramData/otzaria/books/seforim.db"
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "fixtures", "linking", "footnotes", "midrash-vayisau.json")
MAIN_TITLE = "מדרש ויסעו (ילקוט מדרשים)"
NOTES_TITLE = "הערות באותיות על מדרש ויסעו (ילקוט מדרשים)"


def main() -> None:
    import zstandard

    db = sqlite3.connect(f"file:{SRC}?mode=ro", uri=True)
    decoders = {}
    for (raw,) in db.execute("SELECT dict FROM zstd_dict"):
        raw = bytes(raw)
        dict_id = int.from_bytes(raw[4:8], "little") if raw[:4] == b"\x37\xa4\x30\xec" else 0
        decoders[dict_id] = zstandard.ZstdDecompressor(dict_data=zstandard.ZstdCompressionDict(raw))

    def decode(v):
        if v is None:
            return ""
        if isinstance(v, str):
            return v
        b = bytes(v)
        params = zstandard.get_frame_parameters(b)
        return decoders[params.dict_id].decompress(b).decode("utf-8")

    def book(title: str):
        (bid,) = db.execute("SELECT id FROM book WHERE title = ?", (title,)).fetchone()
        rows = db.execute(
            "SELECT l.id, l.lineIndex, l.heRef, c.content FROM line l JOIN line_content c ON c.id = l.id WHERE l.bookId = ? ORDER BY l.lineIndex",
            (bid,),
        ).fetchall()
        return bid, rows

    main_id, main_rows = book(MAIN_TITLE)
    notes_id, notes_rows = book(NOTES_TITLE)
    links = db.execute(
        """SELECT sl.lineIndex, tl.lineIndex FROM link k JOIN line sl ON sl.id = k.sourceLineId JOIN line tl ON tl.id = k.targetLineId
           JOIN connection_type ct ON ct.id = k.connectionTypeId
           WHERE k.sourceBookId = ? AND k.targetBookId = ? AND ct.name = 'FOOTNOTES' ORDER BY 1, 2""",
        (main_id, notes_id),
    ).fetchall()

    def lines(rows):
        return [{"index": i, "heRef": h, "text": decode(c)} for (_, i, h, c) in rows]

    out = {
        "source": "seforim.db (Otzaria library, schema 7); generated by scripts/fixtures/make_footnotes_fixture.py",
        "main": {"title": MAIN_TITLE, "lines": lines(main_rows)},
        "notes": {"title": NOTES_TITLE, "lines": lines(notes_rows)},
        "footnotesLinks": [{"mainLine": a, "notesLine": b} for a, b in links],
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"{len(main_rows)} + {len(notes_rows)} lines, {len(links)} links -> {OUT}")


if __name__ == "__main__":
    main()
