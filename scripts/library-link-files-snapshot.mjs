#!/usr/bin/env node
/*
 * Regenerates src/core/links/library-link-files-snapshot.ts: the names of the `<title>_links.json` files that
 * Otzaria/otzaria-library holds (git ls-tree of the checkout's HEAD). It makes the export's "this book may have a
 * links file in the library" message precise (validate.ts `export/library-file-not-loaded`): the database's
 * `hasSourceLinks` mark is wide (it counts Sefaria's and automatic links), so a book is told apart as "the library
 * has a file of this name" or "the database says it has links, but the library list has no such file". The HOLD
 * itself does not depend on the list being current: it stays whenever the database says the book has links.
 *
 *   node scripts/library-link-files-snapshot.mjs <path to otzaria-library>
 *
 * Only the TITLES are stored (no records, no data): gzipped, base64, decoded once on first use with fflate.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";

const root = process.argv[2];
if (!root) {
  console.error("usage: node scripts/library-link-files-snapshot.mjs <otzaria-library checkout>");
  process.exit(2);
}
const git = (...args) => execFileSync("git", ["-C", root, ...args], { encoding: "utf8", maxBuffer: 256 * 1024 ** 2 });
const commit = git("log", "-1", "--format=%H").trim();
const date = git("log", "-1", "--format=%cs").trim();
const paths = git("ls-tree", "-r", "--name-only", "-z", "HEAD").split("\0").filter((p) => p.endsWith("_links.json"));
const titles = [...new Set(paths.map((p) => p.split("/").at(-1).replace(/_links\.json$/, "")))].sort();
const gz = gzipSync(Buffer.from(titles.join("\n"), "utf8"), { level: 9, mtime: 0 });
// gzip carries an mtime and an OS byte; zero both so the output depends on the list only
gz[4] = gz[5] = gz[6] = gz[7] = 0;
gz[9] = 255;
const lines = gz.toString("base64").match(/.{1,120}/g).map((l) => `  "${l}",`).join("\n");
writeFileSync(
  "src/core/links/library-link-files-snapshot.ts",
  `/* GENERATED by scripts/library-link-files-snapshot.mjs — do not edit. */
/** Otzaria/otzaria-library: the titles of the \`<title>_links.json\` files in the tree (names only). */
export const LIBRARY_LINK_FILES_SNAPSHOT = {
  source: "Otzaria/otzaria-library",
  commit: "${commit}",
  date: "${date}",
  files: ${titles.length},
  /** the titles joined by "\\n", gzip, base64 */
  gzipBase64: [
${lines}
  ].join(""),
} as const;
`,
);
console.log(`${titles.length} titles, ${gz.length} bytes gzipped, from ${commit.slice(0, 8)} (${date})`);
