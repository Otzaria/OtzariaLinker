#!/usr/bin/env node
/*
 * Regenerates src/core/links/sefaria-titles-snapshot.ts from the library's own list of Sefaria-owned
 * titles: `.github/data/sefaria_he_titles.txt` in Otzaria/otzaria-library (an Otzaria organisation
 * repository; the titles are Sefaria's). The PR gate (`validate_manual_links_refs.py`) classifies a
 * target as Sefaria by an exact match in this list, so the tool uses the same list (compatibility
 * review B6). Run it whenever the library refreshes the file:
 *
 *   node scripts/sefaria-titles-snapshot.mjs <path to otzaria-library>
 *
 * The list is stored gzipped as base64 (about 50 KB in the built file instead of 336 KB) and decoded
 * once, on first use, with fflate.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { gzipSync } from "node:zlib";

const root = process.argv[2];
if (!root) {
  console.error("usage: node scripts/sefaria-titles-snapshot.mjs <otzaria-library checkout>");
  process.exit(2);
}
const rel = ".github/data/sefaria_he_titles.txt";
const text = readFileSync(join(root, rel), "utf8");
const git = (...args) => execFileSync("git", ["-C", root, ...args], { encoding: "utf8" }).trim();
const commit = git("log", "-1", "--format=%H", "--", rel);
const date = git("log", "-1", "--format=%cs", "--", rel);
const titles = text.split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
const gz = gzipSync(Buffer.from(titles.join("\n"), "utf8"), { level: 9, mtime: 0 });
// gzip carries an mtime and an OS byte; zero both so the output depends on the list only
gz[4] = gz[5] = gz[6] = gz[7] = 0;
gz[9] = 255;
const b64 = gz.toString("base64");
const lines = b64.match(/.{1,120}/g).map((l) => `  "${l}",`).join("\n");
writeFileSync(
  "src/core/links/sefaria-titles-snapshot.ts",
  `/* GENERATED by scripts/sefaria-titles-snapshot.mjs — do not edit. */
/** Otzaria/otzaria-library ${rel}: the Hebrew titles the library's PR gate counts as Sefaria-owned. */
export const SEFARIA_TITLES_SNAPSHOT = {
  source: "Otzaria/otzaria-library/${rel}",
  commit: "${commit}",
  date: "${date}",
  titles: ${titles.length},
  /** the titles joined by "\\n", gzip, base64 */
  gzipBase64: [
${lines}
  ].join(""),
} as const;
`,
);
console.log(`${titles.length} titles, ${gz.length} bytes gzipped, from ${commit.slice(0, 8)} (${date})`);
