#!/usr/bin/env node
/*
 * Writes src/core/links/sefaria-ref-prefixes.ts: Hebrew heRef prefix → English Sefaria ref prefix
 * (+ the depth-2 offsets of .github/data/sefaria_ref_prefixes.tsv), from the pairs that
 * scripts/sefaria-ref-pairs.py learned from the library's own records (compatibility review B1).
 *
 *   py -I scripts/sefaria-ref-pairs.py <otzaria-library> <seforim.db> <outdir>
 *   node scripts/sefaria-ref-prefixes.mjs <outdir>/prefix_pairs.tsv <otzaria-library>
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [pairsPath, library] = process.argv.slice(2);
if (!pairsPath || !library) {
  console.error("usage: node scripts/sefaria-ref-prefixes.mjs <prefix_pairs.tsv> <otzaria-library>");
  process.exit(2);
}
const offsets = new Map();
for (const line of readFileSync(join(library, ".github/data/sefaria_ref_prefixes.tsv"), "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [p, off] = line.split("\t");
  if (off && off.split(",").some((x) => Number(x) !== 0)) offsets.set(p, off.split(",").map(Number));
}
const rows = [];
for (const line of readFileSync(pairsPath, "utf8").split(/\r?\n/)) {
  if (!line) continue;
  const [he, en, n] = line.split("\t");
  rows.push([he, en, Number(n)]);
}
rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
const commit = execFileSync("git", ["-C", library, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const body = rows.map(([he, en]) => `  [${JSON.stringify(he)}, ${JSON.stringify(en)}${offsets.has(en) ? `, [${offsets.get(en).join(", ")}]` : ""}],`).join("\n");
writeFileSync(
  "src/core/links/sefaria-ref-prefixes.ts",
  `/* GENERATED by scripts/sefaria-ref-prefixes.mjs — do not edit. */
/**
 * Hebrew heRef prefix (as the Otzaria database writes it) → English Sefaria ref prefix (exactly as the
 * Sefaria export index emits it, double spaces included) and the depth-2 offsets of that node. Learned
 * from ${rows.reduce((n, r) => n + r[2], 0).toLocaleString("en")} ref_1/ref_2 of Otzaria/otzaria-library @${commit.slice(0, 8)} against seforim.db
 * (scripts/sefaria-ref-pairs.py); one-to-one in both directions.
 */
export const SEFARIA_REF_PREFIXES: readonly (readonly [he: string, en: string, offsets?: readonly number[]])[] = [
${body}
];
`,
);
console.log(`${rows.length} prefixes`);
